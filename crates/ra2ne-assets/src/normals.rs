/// World-space direction from a surface towards the light (`FUN_00754c00`).
pub const LIGHT_DIRECTION: [f32; 3] = [-0.500011, -0.707106, 0.49998787];

/// `FUN_007586f0` scales `(diffuse + specular)` by this before rounding to a section.
pub const SECTION_SCALE: f32 = 16.0;

/// Normal table selected by the VXL limb normal generation byte.
pub fn table(generation: u8) -> Option<&'static [[f32; 3]]> {
    match generation {
        1 => Some(&GENERATION_1),
        2 => Some(&GENERATION_2),
        3 => Some(&GENERATION_3),
        4 => Some(&GENERATION_4),
        _ => None,
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn engine_table_lengths_and_units() {
        for generation in 1..=4u8 {
            let table = table(generation).unwrap();
            assert!(matches!(table.len(), 16 | 36 | 64 | 245));
            for n in table {
                let len = (n[0] * n[0] + n[1] * n[1] + n[2] * n[2]).sqrt();
                assert!((len - 1.0).abs() < 1e-4, "{generation} {n:?} {len}");
            }
        }
        assert!(table(0).is_none());
        assert!(table(5).is_none());
    }
    #[test]
    fn light_direction_matches_engine_constants() {
        let l = LIGHT_DIRECTION;
        let len = (l[0] * l[0] + l[1] * l[1] + l[2] * l[2]).sqrt();
        assert!((len - 1.0).abs() < 1e-5);
        assert!((l[0] + 0.5).abs() < 1e-3 && (l[1] + 0.70710678).abs() < 1e-3);
        assert!((l[2] - 0.5).abs() < 1e-3);
        assert_eq!(SECTION_SCALE, 16.0);
    }
}
