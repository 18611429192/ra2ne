//! Voxel lighting normal tables and the fixed light direction of the original
//! engine (gamemd.exe 1.001).
//!
//! `gamemd.exe` keeps four normal tables for the four VXL normal generations
//! (the limb footer byte this crate parses as `normal_mode`): 16, 36, 64 and
//! 245 entries. The descriptor with the table pointers sits at 0x8469e4
//! (pointer, 0, pointer, pointer, pointer, then the counts 16/36/64/245 at
//! 0x8469f8); the tables themselves follow at 0x846a08, 0x846ac8, 0x846c78 and
//! 0x846f78 as 12-byte float triples. `FUN_007586f0` walks the selected table
//! together with the model-space light direction to build the per-model shade
//! table that indexes the sections of `voxels.vpl`.
//!
//! Values are transcribed from the supplied `Ra2Game412/gamemd.exe`
//! (sha256 `7b8a068535d6af06845edf95ae829b113d00c02909330e16f197426cd7db94b6`); `docs/REA_SETUP.md` records the addresses and how to
//! re-extract them. The light direction reproduces `FUN_00754c00`: the base vector
//! (-1/sqrt(2), -1/sqrt(2), 0) is pushed as the immediate 0xbf3504e6 at 0x754c32
//! and rotated about index-Y by the constant at 0x7e1e68 (0.785375) before the
//! result is stored at 0x887470. `FUN_00753d00` additionally transforms the world
//! up vector (0, 0, 1) with the same matrix for the specular half vector, and the
//! 16x section scale lives at 0x7f6960.

